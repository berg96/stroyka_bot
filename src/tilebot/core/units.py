"""Единицы измерения в тексте для мастера.

Шов мастер меряет в десятых миллиметра («полтора», «1,4»), а показывать его
целыми — врать: 1,4 превращалось в «1 мм», и выглядело так, будто бот ввод
проигнорировал.
"""


def fmt_mm(value: float) -> str:
    """Миллиметры так, как их пишет мастер: 2 → «2», 1.4 → «1,4»."""
    text = f"{value:.1f}".rstrip("0").rstrip(".")
    return text.replace(".", ",") or "0"
